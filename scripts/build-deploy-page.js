/**
 * Packages the compiled image renderer contracts for the deploy page in
 * deploy/. Run `npx hardhat compile` first (the deploy-page npm script does).
 *
 * Writes (both git-ignored):
 *   deploy/contracts.js      ABIs, creation bytecode, and what each deployed
 *                            contract's code must look like, for the page
 *   deploy/standard-input.json  solc Standard-JSON input, for verifying the
 *                            deployed contracts on Etherscan
 *
 * Fails unless the contracts were compiled with the settings the tests ran
 * against, so the page always deploys the tested bytecode.
 */
const fs = require('fs');
const path = require('path');
const { pack, CHUNK_SIZE } = require('./pack-layer-data');

const ROOT = path.join(__dirname, '..');
const OUT = path.join(ROOT, 'deploy');

const SOLC = '0.8.20+commit.a1b79de6';
const OPTIMIZER_RUNS = 200;

const CONTRACTS = [
  'RadioactivePunksLayerData1',
  'RadioactivePunksLayerData2',
  'RadioactivePunksImage',
  'RadioactivePunksJSONV2',
];

function load(name) {
  const dir = path.join(ROOT, 'artifacts', 'contracts', `${name}.sol`);
  const artifact = JSON.parse(fs.readFileSync(path.join(dir, `${name}.json`), 'utf8'));
  const dbg = JSON.parse(fs.readFileSync(path.join(dir, `${name}.dbg.json`), 'utf8'));
  const buildInfo = JSON.parse(fs.readFileSync(path.join(dir, dbg.buildInfo), 'utf8'));

  const { optimizer } = buildInfo.input.settings;
  if (buildInfo.solcLongVersion !== SOLC || !optimizer.enabled || optimizer.runs !== OPTIMIZER_RUNS) {
    throw new Error(`${name} was compiled with solc ${buildInfo.solcLongVersion}, optimizer ${JSON.stringify(optimizer)}; expected ${SOLC} with ${OPTIMIZER_RUNS} runs`);
  }

  const compiled = buildInfo.output.contracts[`contracts/${name}.sol`][name];
  return { artifact, buildInfo, compiled };
}

function main() {
  const loaded = Object.fromEntries(CONTRACTS.map((name) => [name, load(name)]));

  // the layer data contracts' code is the packed data itself, behind a STOP byte
  const blob = pack().blob;
  const layerCode = (i) => '0x00' + blob.subarray(i * CHUNK_SIZE, (i + 1) * CHUNK_SIZE).toString('hex');

  const contracts = {};
  for (const [name, { artifact, compiled }] of Object.entries(loaded)) {
    const entry = {
      abi: artifact.abi,
      bytecode: artifact.bytecode,
      // deployed code must equal this, with immutable values zeroed out
      expectedCode: artifact.deployedBytecode,
      immutableRanges: Object.values(compiled.evm.deployedBytecode.immutableReferences || {}).flat(),
    };
    if (name === 'RadioactivePunksLayerData1') entry.expectedCode = layerCode(0);
    if (name === 'RadioactivePunksLayerData2') entry.expectedCode = layerCode(1);
    contracts[name] = entry;
  }

  // one compile job built all four, so one Standard-JSON input verifies them all
  const buildInfos = new Set(Object.values(loaded).map((l) => l.buildInfo.id));
  const { buildInfo } = loaded.RadioactivePunksImage;

  fs.mkdirSync(OUT, { recursive: true });
  fs.writeFileSync(
    path.join(OUT, 'contracts.js'),
    `// Generated by scripts/build-deploy-page.js. Do not edit by hand.\n` +
    `export const COMPILER = ${JSON.stringify({
      solc: SOLC,
      optimizerRuns: OPTIMIZER_RUNS,
      evmVersion: buildInfo.input.settings.evmVersion || 'default (shanghai)',
      standardInput: buildInfos.size === 1 ? 'standard-input.json' : null,
    }, null, 2)};\n` +
    `export const CONTRACTS = ${JSON.stringify(contracts)};\n`
  );

  if (buildInfos.size === 1) {
    fs.writeFileSync(path.join(OUT, 'standard-input.json'), JSON.stringify(buildInfo.input));
  } else {
    fs.rmSync(path.join(OUT, 'standard-input.json'), { force: true });
    console.warn('Contracts came from different compile jobs; run `npx hardhat clean && npx hardhat compile` for a single Etherscan Standard-JSON input.');
  }

  for (const [name, c] of Object.entries(contracts)) {
    console.log(`${name.padEnd(28)} creation ${((c.bytecode.length - 2) / 2).toString().padStart(6)} bytes, code ${((c.expectedCode.length - 2) / 2).toString().padStart(6)} bytes`);
  }
  console.log(`solc ${SOLC}, optimizer ${OPTIMIZER_RUNS} runs -> deploy/contracts.js`);
}

main();
